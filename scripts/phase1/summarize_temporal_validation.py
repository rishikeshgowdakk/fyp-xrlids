#!/usr/bin/env python
"""Compare a row-level random split with a strict temporal holdout (GAP-P06).

Reads the saved Phase 1 experiment artifacts and emits a reproducible markdown
comparison. The two test populations are different by construction, so the
comparison is descriptive: the random-split test is drawn from the same capture
days as training, while the temporal test is strictly later. Per-family
detection rates are reported separately so unseen attack families are visible.

Usage::

    python scripts/phase1/summarize_temporal_validation.py \
        --random-experiment results/experiments/EXP-P1-CSE2018-R10-MULTI-001 \
        --temporal-experiment results/experiments/EXP-P1-CSE2018-TEMPORAL-R10-001 \
        --out reports/generated/temporal_split_report.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

import pandas as pd  # noqa: E402

METRICS = ("accuracy", "precision", "recall", "f1", "roc_auc")


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _metric(exp_dir: Path, model: str = "random_forest") -> dict[str, Any]:
    metrics = _read_json(exp_dir / "test_metrics.json")
    aligned = metrics.get("aligned", {}).get("models", {})
    result = aligned.get(model)
    if result is None:
        raise SystemExit(f"{exp_dir}: no aligned metrics for model '{model}'")
    return result


def _split_summary(exp_dir: Path) -> dict[str, Any]:
    manifest = _read_json(exp_dir / "split_manifest.json")
    record = _read_json(exp_dir / "experiment_record.json")
    return {
        "methodology": manifest.get("methodology"),
        "counts": manifest.get("counts", {}),
        "observed_ratios": manifest.get("observed_ratios", {}),
        "class_distribution": manifest.get("class_distribution", {}),
        "temporal": manifest.get("temporal"),
        "rows_total": record.get("rows_total"),
        "rows_train": record.get("rows_train"),
        "rows_validation": record.get("rows_validation"),
        "rows_test": record.get("rows_test"),
    }


def _family_table(exp_dir: Path) -> dict[str, dict[str, Any]]:
    path = exp_dir / "per_family_metrics.csv"
    if not path.is_file():
        return {}
    frame = pd.read_csv(path)
    return {
        str(row["family"]): {
            "support": int(row["support"]),
            "detection_rate": float(row["detection_rate"]),
            "error_rate": float(row["error_rate"]),
        }
        for _, row in frame.iterrows()
        if bool(row["is_attack"])
    }


def _fmt(value: Any, digits: int = 4) -> str:
    return "—" if value is None else f"{float(value):.{digits}f}"


def main() -> int:
    parser = argparse.ArgumentParser(description="Compare random-split and temporal-holdout runs")
    parser.add_argument(
        "--random-experiment",
        type=Path,
        default=Path("results/experiments/EXP-P1-CSE2018-R10-MULTI-001"),
    )
    parser.add_argument(
        "--temporal-experiment",
        type=Path,
        default=Path("results/experiments/EXP-P1-CSE2018-TEMPORAL-R10-001"),
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("reports/generated/temporal_split_report.md"),
    )
    args = parser.parse_args()

    random_dir: Path = args.random_experiment
    temporal_dir: Path = args.temporal_experiment
    if not (random_dir / "test_metrics.json").is_file():
        print(f"missing random-split artifacts: {random_dir}", file=sys.stderr)
        return 1
    if not (temporal_dir / "test_metrics.json").is_file():
        print(f"missing temporal-split artifacts: {temporal_dir}", file=sys.stderr)
        return 1

    random_metrics = _metric(random_dir)
    temporal_metrics = _metric(temporal_dir)
    random_split = _split_summary(random_dir)
    temporal_split = _split_summary(temporal_dir)
    random_families = _family_table(random_dir)
    temporal_families = _family_table(temporal_dir)
    temporal_population = _read_json(temporal_dir / "experiment_population.json")
    temporal_accounting = temporal_population.get("accounting", {}).get("aggregate", {})

    delta = {
        metric: float(temporal_metrics.get(metric, 0.0)) - float(random_metrics.get(metric, 0.0))
        for metric in METRICS
    }

    lines = [
        "# Temporal Holdout Validation (generated)",
        "",
        "Comparison between the row-level random split and a strict future-day temporal",
        "holdout on CSE-CIC-IDS2018 under the frozen R10 feature contract. Generated by",
        "`scripts/phase1/summarize_temporal_validation.py` from saved experiment artifacts.",
        "",
        "## Split design",
        "",
        "| Experiment | Split methodology | Train | Validation | Test | Test attack fraction | Test time window |",
        "|:---|:---|:---:|:---:|:---:|:---:|:---|",
    ]

    def _attack_fraction(summary: dict[str, Any]) -> str:
        test = summary.get("class_distribution", {}).get("test", {})
        value = test.get("attack_fraction")
        return "—" if value is None else f"{float(value):.2%}"

    random_window = "all capture days (row-level random)"
    temporal_window = "—"
    temporal_info = temporal_split.get("temporal") or {}
    ranges = temporal_info.get("ranges") or {}
    if ranges:
        temporal_window = f"{ranges.get('test', {}).get('min', '—')} → {ranges.get('test', {}).get('max', '—')}"
    lines.append(
        f"| Random split | {random_split.get('methodology', '—')} | "
        f"{random_split.get('rows_train', 0):,} | {random_split.get('rows_validation', 0):,} | "
        f"{random_split.get('rows_test', 0):,} | {_attack_fraction(random_split)} | {random_window} |"
    )
    lines.append(
        f"| Temporal holdout | {temporal_split.get('methodology', '—')} | "
        f"{temporal_split.get('rows_train', 0):,} | {temporal_split.get('rows_validation', 0):,} | "
        f"{temporal_split.get('rows_test', 0):,} | {_attack_fraction(temporal_split)} | {temporal_window} |"
    )

    lines.extend([
        "",
        "The temporal holdout sorts rows by the real capture `Timestamp` and cuts at hour",
        "boundaries. Test rows are strictly later than validation rows; validation rows are",
        "strictly later than training rows. No class stratification is applied.",
        "",
    ])
    if ranges:
        lines.append(
            f"The training window ends at `{ranges.get('train', {}).get('max', '—')}` and the "
            f"test window starts at `{ranges.get('test', {}).get('min', '—')}`. The later CSE "
            "capture days contain infiltration and bot traffic that are absent from the earlier "
            "training days, so the per-family table is the key unseen-family evidence."
        )
        lines.append("")

    test_class = temporal_split.get("class_distribution", {}).get("test", {})
    test_attacks = test_class.get("attack")
    test_benign = test_class.get("benign")
    if test_attacks is not None and test_benign is not None:
        test_total = int(test_attacks) + int(test_benign)
        removed_conflicts = int(temporal_accounting.get("removed_label_conflicts", 0) or 0)
        removed_dupes = int(temporal_accounting.get("removed_feature_duplicates", 0) or 0)
        lines.extend([
            "**Why the temporal test attack fraction is low.** "
            f"The temporal test contains {int(test_attacks):,} attacks out of {test_total:,} rows "
            f"({int(test_attacks) / max(1, test_total):.2%}). This is the **deduplicated, "
            "conflict-free modelling population**, not the raw future-period prevalence. Before "
            f"splitting, Policy A removed {removed_conflicts:,} label-conflicting rows and "
            f"{removed_dupes:,} duplicate feature vectors globally. Many later bot and infiltration "
            "flows were exact feature duplicates of earlier rows or conflicted with benign labels; "
            "the surviving future attacks are the genuinely new, conflict-free cases. The per-family "
            "comparison is therefore a harder test than the raw day-level attack ratio suggests.",
            "",
        ])

    lines.extend([
        "## Overall held-out metrics (Random Forest)",
        "",
        "| Metric | Random split | Temporal holdout | Δ (temporal − random) |",
        "|:---|:---:|:---:|:---:|",
    ])
    for metric in METRICS:
        lines.append(
            f"| {metric} | {_fmt(random_metrics.get(metric))} | "
            f"{_fmt(temporal_metrics.get(metric))} | {delta[metric]:+.4f} |"
        )

    lines.extend([
        "",
        "The two test populations are not the same rows. The random-split test is drawn",
        "from the same capture days as training; the temporal test is a future-day holdout.",
        "The Δ column is therefore descriptive, not a paired statistical test.",
        "",
        "## Per-attack-family detection rates (Random Forest, τ = 0.50)",
        "",
        "| Attack family | Random support | Random detection | Temporal support | Temporal detection | Δ detection |",
        "|:---|:---:|:---:|:---:|:---:|:---:|",
    ])

    all_families = sorted(set(random_families) | set(temporal_families))
    for family in all_families:
        r = random_families.get(family)
        t = temporal_families.get(family)
        r_rate = r["detection_rate"] if r else None
        t_rate = t["detection_rate"] if t else None
        if r_rate is not None and t_rate is not None:
            d = f"{t_rate - r_rate:+.4f}"
        else:
            d = "—"
        lines.append(
            f"| {family} | {r['support']:,} | {_fmt(r_rate)} | "
            f"{t['support']:,} | {_fmt(t_rate)} | {d} |"
            if r and t
            else f"| {family} | {r['support']:,} | {_fmt(r_rate)} | — | — | — |"
            if r
            else f"| {family} | — | — | {t['support']:,} | {_fmt(t_rate)} | — |"
        )

    # Families that occur in both test populations are the cleanest comparison:
    # the support differs, but the same detector is being asked about the same
    # attack family on same-day (random) vs future (temporal) rows.
    both = sorted(set(random_families) & set(temporal_families))
    collapse = []
    for family in both:
        r = random_families[family]
        t = temporal_families[family]
        collapse.append(
            f"| `{family}` | {r['support']:,} | {r['detection_rate']:.2%} | "
            f"{t['support']:,} | {t['detection_rate']:.2%} | "
            f"{t['detection_rate'] - r['detection_rate']:+.2%} |"
        )
    if collapse:
        lines.extend([
            "",
            "### Seen-family detection collapse",
            "",
            "The following attack families occur in both test populations. The temporal rows are",
            "later and conflict-free, so the same labels test genuinely new flows rather than",
            "same-day near-duplicates. A large drop is direct evidence of split optimism:",
            "",
            "| Attack family | Random support | Random detection | Temporal support | Temporal detection | Δ |",
            "|:---|:---:|:---:|:---:|:---:|:---:|",
            *collapse,
        ])

    lines.extend([
        "",
        "## Interpretation guardrails",
        "",
        "- The random split is the in-domain benchmark used throughout Phase 1. It is not",
        "  replaced by the temporal holdout; the two answer different questions.",
        "- The temporal holdout is a stricter estimate of future-day performance and exposes",
        "  how much of the random-split result depends on same-day near-duplicate structure.",
        "- Aggregate temporal F1 can be lower because the held-out period contains attack",
        "  families that never appear in training. The per-family table separates seen and",
        "  unseen families rather than hiding the difference in one number.",
        "- No threshold was tuned on the temporal test set. The research threshold remains",
        "  τ = 0.50 (D-003 open).",
        "",
        "## Artifact locations",
        "",
        f"- Random split: `{random_dir}/`",
        f"- Temporal holdout: `{temporal_dir}/`",
        f"- Machine-readable comparison: `{temporal_dir}/temporal_validation.json`",
        "",
    ])

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    unseen = sorted(set(temporal_families) - set(random_families))
    payload = {
        "random_experiment": str(random_dir),
        "temporal_experiment": str(temporal_dir),
        "metric_model": "random_forest",
        "threshold": 0.5,
        "random_split": random_split,
        "temporal_split": temporal_split,
        "random_metrics": {metric: random_metrics.get(metric) for metric in METRICS},
        "temporal_metrics": {metric: temporal_metrics.get(metric) for metric in METRICS},
        "delta": delta,
        "per_family": {
            "random": random_families,
            "temporal": temporal_families,
        },
        "unseen_in_temporal": unseen,
    }
    (temporal_dir / "temporal_validation.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Wrote {args.out}")
    print(f"Wrote {temporal_dir / 'temporal_validation.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
